function getTagNameByWord(wordIndex) {
  const tag = TAGS_DICT.find(t => t.word === wordIndex && t.bit === null);
  if (tag) return tag.name;
  const bits = TAGS_DICT.filter(t => t.word === wordIndex && t.bit !== null);
  if (bits.length > 0) return 'Word de Bits';
  return 'W_FREE';
}
